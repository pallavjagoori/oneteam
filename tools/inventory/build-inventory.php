<?php

/**
 * Chatwoot feature inventory builder.
 *
 * Walks a Chatwoot checkout, assigns every backend file, spec, frontend file,
 * HTTP route, database table and feature flag to exactly one feature from
 * features.json, and writes the result as Markdown under docs/inventory.
 *
 * The run fails (exit code 1) when anything is left unassigned, so the
 * inventory is guaranteed to cover the whole Chatwoot codebase. Re-run it on
 * every new Chatwoot release to see what moved.
 *
 * Usage:
 *   php tools/inventory/build-inventory.php \
 *       --source=/path/to/chatwoot \
 *       --routes=/path/to/routes.txt \
 *       [--rules=tools/inventory/features.json] \
 *       [--out=docs/inventory]
 *
 * routes.txt is the output of `bin/rails routes`; see generate-routes.sh.
 */

declare(strict_types=1);

require __DIR__ . '/inventory-functions.php';

$options = getopt('', ['source:', 'routes:', 'rules::', 'out::']);
$source = rtrim($options['source'] ?? '', '/');
$routesFile = $options['routes'] ?? '';
$rulesFile = $options['rules'] ?? __DIR__ . '/features.json';
$outDir = rtrim($options['out'] ?? 'docs/inventory', '/');

if ($source === '' || !is_dir($source) || !is_file($routesFile)) {
    fwrite(STDERR, "Usage: php build-inventory.php --source=<chatwoot dir> --routes=<routes.txt>\n");
    exit(2);
}

$rules = json_decode((string) file_get_contents($rulesFile), true, 512, JSON_THROW_ON_ERROR);
$features = $rules['features'];
$ignore = $rules['ignore'];

// Collect every unit and assign it to a feature.
$byFeature = [];
foreach ($features as $feature) {
    $byFeature[$feature['id']] = [
        'backend' => [], 'specs' => [], 'frontend' => [], 'routes' => [], 'tables' => [], 'flags' => [],
    ];
}
$unassigned = ['backend' => [], 'specs' => [], 'frontend' => [], 'routes' => [], 'tables' => [], 'flags' => []];

$assign = static function (
    string $bucket,
    string $subject,
    mixed $item,
    string $key = 'paths'
) use (
    $features,
    &$byFeature,
    &$unassigned
): void {
    $id = classify($subject, $features, $key);
    if ($id === null) {
        $unassigned[$bucket][] = $subject;

        return;
    }
    $byFeature[$id][$bucket][] = $item;
};

foreach (BACKEND_ROOTS as $root) {
    foreach (listFiles($source, $root) as $path) {
        if (str_starts_with($path, FRONTEND_ROOT . '/') || isIgnored($path, $ignore)) {
            continue;
        }
        $assign('backend', $path, $path);
    }
}

foreach (SPEC_ROOTS as $root) {
    foreach (listFiles($source, $root) as $path) {
        if (!str_ends_with($path, '_spec.rb')) {
            continue;
        }
        // spec/enterprise/models/foo_spec.rb is classified like enterprise/app/models/foo.rb,
        // and spec/lib/foo_spec.rb like lib/foo.rb.
        $subject = preg_replace(
            ['#^spec/(enterprise/)?lib/#', '#^spec/(enterprise/)?(?!lib/)#'],
            ['$1lib/', '$1app/'],
            $path
        );
        $id = classify((string) $subject, $features);
        if ($id === null) {
            $unassigned['specs'][] = $path;
            continue;
        }
        $byFeature[$id]['specs'][] = $path;
    }
}

$localeFiles = 0;
foreach (listFiles($source, FRONTEND_ROOT) as $path) {
    // Translations follow their screens and are kept as they are, so they are counted, not assigned.
    if (preg_match('#/i18n/#', $path) === 1) {
        $localeFiles++;
        continue;
    }
    if (isIgnored($path, $ignore)) {
        continue;
    }
    $assign('frontend', $path, $path);
}

$routes = parseRoutes($routesFile);
foreach ($routes as $route) {
    $assign('routes', routeSubject($route), $route);
}

foreach (parseTables($source) as $table) {
    $assign('tables', $table, $table, 'tables');
}

foreach (parseFlags($source) as $flag) {
    $assign('flags', $flag, $flag, 'flags');
}

// Write the Markdown output.
@mkdir($outDir . '/features', 0777, true);
foreach (glob($outDir . '/features/*.md') ?: [] as $stale) {
    unlink($stale);
}

$summary = [];
$summary[] = '# Chatwoot feature inventory';
$summary[] = '';
$summary[] = 'Generated by `tools/inventory/build-inventory.php` from Chatwoot ' . trim(
    (string) @file_get_contents($source . '/VERSION_CW')
) . '. Do not edit by hand: change `tools/inventory/features.json` and re-run the script.';
$summary[] = '';
$summary[] = 'Every backend file, Ruby spec, frontend file, HTTP route, database table and feature flag in Chatwoot is '
    . 'assigned to exactly one feature below. "EE" counts the parts that live in Chatwoot\'s `enterprise/` folder.';
$summary[] = '';

$totals = ['routes' => 0, 'backend' => 0, 'ee' => 0, 'specs' => 0, 'frontend' => 0, 'tables' => 0];
$rows = [];
$currentArea = null;
foreach ($features as $feature) {
    $data = $byFeature[$feature['id']];
    $eeFiles = count(array_filter($data['backend'], 'isEnterprise'));
    $totals['routes'] += count($data['routes']);
    $totals['backend'] += count($data['backend']);
    $totals['ee'] += $eeFiles;
    $totals['specs'] += count($data['specs']);
    $totals['frontend'] += count($data['frontend']);
    $totals['tables'] += count($data['tables']);

    if ($feature['area'] !== $currentArea) {
        $currentArea = $feature['area'];
        $rows[] = '';
        $rows[] = '## ' . $currentArea;
        $rows[] = '';
        $rows[] = '| Feature | Routes | Backend files (EE) | Ruby specs | Frontend files | Tables |';
        $rows[] = '| --- | ---: | ---: | ---: | ---: | ---: |';
    }
    $rows[] = sprintf(
        '| [%s](features/%s.md) | %d | %d (%d) | %d | %d | %d |',
        $feature['name'],
        $feature['id'],
        count($data['routes']),
        count($data['backend']),
        $eeFiles,
        count($data['specs']),
        count($data['frontend']),
        count($data['tables'])
    );

    $page = renderFeature($feature, $data);
    file_put_contents($outDir . '/features/' . $feature['id'] . '.md', $page);
}

$summary[] = '## Totals';
$summary[] = '';
$areaCount = count(array_unique(array_column($features, 'area')));
$summary[] = sprintf('- %d features in %d areas', count($features), $areaCount);
$summary[] = sprintf('- %d HTTP routes', $totals['routes']);
$summary[] = sprintf('- %d backend files, %d of them enterprise', $totals['backend'], $totals['ee']);
$summary[] = sprintf('- %d Ruby spec files', $totals['specs']);
$summary[] = sprintf('- %d frontend files, plus %d translation files', $totals['frontend'], $localeFiles);
$summary[] = sprintf('- %d database tables, %d feature flags', $totals['tables'], count(parseFlags($source)));
$summary = array_merge($summary, $rows);
file_put_contents($outDir . '/README.md', implode("\n", $summary) . "\n");

$missing = array_sum(array_map('count', $unassigned));
if ($missing > 0) {
    foreach ($unassigned as $bucket => $items) {
        foreach ($items as $item) {
            fwrite(STDERR, "unassigned {$bucket}: {$item}\n");
        }
    }
    fwrite(STDERR, "{$missing} items are not assigned to a feature. Add patterns to features.json.\n");
    exit(1);
}

fwrite(STDOUT, sprintf("Inventory written to %s: %d features, nothing unassigned.\n", $outDir, count($features)));
