<?php

/**
 * Helper functions for coverage-by-feature.php.
 *
 * Kept apart from the runner so this file only declares symbols (PSR-1).
 */

declare(strict_types=1);

/**
 * Reads an lcov file into [path => [covered lines, total lines]].
 *
 * @return array<string, array{int, int}>
 */
function parseLcov(string $file): array
{
    $files = [];
    $path = null;
    foreach (file($file, FILE_IGNORE_NEW_LINES) ?: [] as $line) {
        if (str_starts_with($line, 'SF:')) {
            $path = normalisePath(substr($line, 3));
            $files[$path] = [0, 0];
        } elseif ($path !== null && str_starts_with($line, 'LF:')) {
            $files[$path][1] = (int) substr($line, 3);
        } elseif ($path !== null && str_starts_with($line, 'LH:')) {
            $files[$path][0] = (int) substr($line, 3);
        }
    }

    return $files;
}

/**
 * Reads SimpleCov's .resultset.json into [path => [covered lines, total lines]].
 *
 * A line counts when SimpleCov tracks it (its hit count is not null), and is
 * covered when it was hit at least once. Results from several runs are merged.
 *
 * @return array<string, array{int, int}>
 */
function parseSimpleCov(string $file): array
{
    $data = json_decode((string) file_get_contents($file), true, 512, JSON_THROW_ON_ERROR);
    $hits = [];
    foreach ($data as $run) {
        foreach ($run['coverage'] as $absolute => $coverage) {
            $path = normalisePath($absolute);
            foreach ($coverage['lines'] ?? $coverage as $index => $count) {
                if ($count === null) {
                    continue;
                }
                $hits[$path][$index] = ($hits[$path][$index] ?? 0) + $count;
            }
        }
    }

    $files = [];
    foreach ($hits as $path => $lines) {
        $files[$path] = [count(array_filter($lines, static fn (int $count): bool => $count > 0)), count($lines)];
    }
    ksort($files);

    return $files;
}

/** Makes a path relative to the Chatwoot checkout. */
function normalisePath(string $path): string
{
    return (string) preg_replace('#^.*?/chatwoot/#', '', $path);
}

/** Formats covered/total as a percentage, or a dash when nothing is tracked. */
function percent(int $covered, int $total): string
{
    return $total === 0 ? '–' : number_format(100 * $covered / $total, 1) . '%';
}

/**
 * Sums [covered, total] over a list of [path, covered, total] rows.
 *
 * @param list<array{string, int, int}> $rows
 * @return array{int, int}
 */
function sumRows(array $rows): array
{
    return [array_sum(array_column($rows, 1)), array_sum(array_column($rows, 2))];
}

/**
 * Writes docs/coverage/README.md and one gap page per feature.
 *
 * @param list<array<string, mixed>> $features
 * @param array<string, array<string, list<array{string, int, int}>>> $byFeature
 * @param list<string> $suiteNames
 * @param array<string, array<string, array{int, int}>> $suites
 */
function writeCoverageReport(string $outDir, array $features, array $byFeature, array $suiteNames, array $suites): void
{
    @mkdir($outDir . '/features', 0777, true);
    foreach (glob($outDir . '/features/*.md') ?: [] as $stale) {
        unlink($stale);
    }

    $out = ['# Chatwoot test coverage by feature', ''];
    $out[] = 'Generated by `tools/coverage/coverage-by-feature.php` from the coverage that `upstream/run-tests.sh` '
        . 'collects. Line coverage only. Features follow the [feature inventory](../inventory/README.md).';
    $out[] = '';
    foreach ($suiteNames as $suite) {
        [$covered, $total] = sumRows(array_map(
            static fn (string $path, array $counts): array => [$path, $counts[0], $counts[1]],
            array_keys($suites[$suite]),
            array_values($suites[$suite])
        ));
        $out[] = sprintf(
            '- **%s:** %s of lines covered (%d of %d)',
            ucfirst($suite),
            percent($covered, $total),
            $covered,
            $total
        );
    }
    $out[] = '';

    $header = '| Feature |';
    $rule = '| --- |';
    foreach ($suiteNames as $suite) {
        $header .= ' ' . ucfirst($suite) . ' | ' . ucfirst($suite) . ' files below 100% |';
        $rule .= ' ---: | ---: |';
    }
    $out[] = $header;
    $out[] = $rule;

    $ids = array_column($features, 'id');
    if (isset($byFeature['unassigned'])) {
        $ids[] = 'unassigned';
    }
    $names = array_column($features, 'name', 'id') + ['unassigned' => 'Not matched by any feature'];

    foreach ($ids as $id) {
        $row = sprintf('| [%s](features/%s.md) |', $names[$id], $id);
        $page = ['# ' . $names[$id] . ': coverage gaps', ''];
        foreach ($suiteNames as $suite) {
            $rows = $byFeature[$id][$suite] ?? [];
            [$covered, $total] = sumRows($rows);
            $gaps = array_values(array_filter($rows, static fn (array $r): bool => $r[1] < $r[2]));
            $row .= sprintf(' %s | %d |', percent($covered, $total), count($gaps));

            $page[] = sprintf(
                '## %s: %s (%d of %d lines)',
                ucfirst($suite),
                percent($covered, $total),
                $covered,
                $total
            );
            $page[] = '';
            if ($gaps === []) {
                $page[] = $rows === [] ? 'No tracked files.' : 'Every file is fully covered.';
            } else {
                $page[] = '| File | Coverage | Uncovered lines |';
                $page[] = '| --- | ---: | ---: |';
                usort($gaps, static fn (array $a, array $b): int => ($b[2] - $b[1]) <=> ($a[2] - $a[1]));
                foreach ($gaps as [$path, $fileCovered, $fileTotal]) {
                    $uncovered = $fileTotal - $fileCovered;
                    $page[] = sprintf('| `%s` | %s | %d |', $path, percent($fileCovered, $fileTotal), $uncovered);
                }
            }
            $page[] = '';
        }
        $out[] = $row;
        file_put_contents($outDir . '/features/' . $id . '.md', implode("\n", $page));
    }

    file_put_contents($outDir . '/README.md', implode("\n", $out) . "\n");
}
